Module PinnedEnums.
  Inductive assoc : Type := Left | Right | None.
  Inductive arity : Type := Zero | One | Two.
  Inductive overflow : Type := Panic | Wrap | Unchecked | NotApplicable.
  Inductive ordering : Type := Less | Equal | Greater.
