(* ------------------------------------------------------------------ *)
(* The pinned ASCII key type (subset v2.6): a list of ASCII code       *)
(* points. Extraction target: &'static str (the pinned mapping; the    *)
(* DIF discharges the mapping over the complete pinned key domain).    *)
(* ------------------------------------------------------------------ *)

Definition key : Type := (list nat).

(* Pinned key equality: bounded-fuel structural recursion (v2.7). The  *)
(* fuel-0 arm is the pinned total default (both lists consumed within  *)
(* fuel); every pinned key has length <= 25 < 32 = the pinned fuel.    *)
Fixpoint key_eq_aux (fuel : nat) (a b : key) : bool :=
  match fuel with
  | 0 => true
  | S f =>
      match a with
      | nil => match b with nil => true | cons _ _ => false end
      | cons x xs =>
          match b with
          | nil => false
          | cons y ys => andb (Nat.eqb x y) (key_eq_aux f xs ys)
          end
      end
  end.

Definition key_eq (a b : key) : bool := key_eq_aux 32 a b.

(* Pinned byte-lexicographic strict order: bounded-fuel structural     *)
(* recursion (v2.7). The fuel-0 arm is the pinned total default.       *)
Fixpoint key_lt_aux (fuel : nat) (a b : key) : bool :=
  match fuel with
  | 0 => false
  | S f =>
      match a with
      | nil => match b with nil => false | cons _ _ => true end
      | cons x xs =>
          match b with
          | nil => false
          | cons y ys =>
              if Nat.ltb x y then true
              else if Nat.ltb y x then false
              else key_lt_aux f xs ys
          end
      end
  end.

Definition key_lt (a b : key) : bool := key_lt_aux 32 a b.

(* ------------------------------------------------------------------ *)
(* Pinned laws (kernel-checked, zero admits).                          *)
(* ------------------------------------------------------------------ *)

(* L1: the two key functions are definitional applications of their    *)
(* fuel fixpoints at the pinned fuel (holds for every key).            *)
Lemma key_eq_is_pinned_fuel : forall a b : key,
  key_eq a b = key_eq_aux 32 a b.
Proof. reflexivity. Qed.

Lemma key_lt_is_pinned_fuel : forall a b : key,
  key_lt a b = key_lt_aux 32 a b.
Proof. reflexivity. Qed.

(* L2: key equality is reflexive on the pinned key shapes that appear  *)
(* as one-byte lists and the empty list (the sweep base domain).       *)
Lemma key_eq_refl_base : forallb (fun n => key_eq (cons n nil) (cons n nil)) (seq 0 128) = true.
Proof. vm_compute. reflexivity. Qed.

(* L3: byte-lexicographic strict order agrees with the numeric order    *)
(* of the single-byte ASCII codes over the complete ASCII range.        *)
Lemma key_lt_single_byte_agrees_numeric :
  forallb (fun p => orb (Nat.eqb (fst p) (snd p))
                        (eqb (key_lt (cons (fst p) nil) (cons (snd p) nil))
                             (Nat.ltb (fst p) (snd p))))
          (flat_map (fun i => map (fun j => (i, j)) (seq 0 128)) (seq 0 128)) = true.
Proof. vm_compute. reflexivity. Qed.
