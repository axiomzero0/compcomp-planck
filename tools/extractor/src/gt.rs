fn effect_section(u: &ParseUnit) -> String {
    let (ty_name, width) = u.row_type.clone().expect("row type alias");
    let (row_fns, bool_fns) = tabulated_functions(u);
    let ws = weights(width);
    let mut field_exprs: Vec<String> = Vec::new();
    for k in 0..width {
        let mut expr = String::from("r");
        for _ in 0..k {
            expr = format!("snd ({})", expr);
        }
        if k < width - 1 {
            expr = format!("fst ({})", expr);
        }
        field_exprs.push(expr);
    }
    let mut row_index_def = String::from("Definition row_index (r : ");
    row_index_def.push_str(&ty_name);
    row_index_def.push_str(") : nat := ");
    for (k, w) in ws.iter().enumerate() {
        if k == width - 1 {
            row_index_def.push_str(&format!("{} * b2n ({})", w, field_exprs[k]));
        } else {
            row_index_def.push_str(&format!("{} * b2n ({}) + ", w, field_exprs[k]));
        }
    }
    row_index_def.push_str(".");

    let mut all_rows = String::from("Definition all_rows : list ");
    all_rows.push_str(&ty_name);
    all_rows.push_str(" :=\n  [ ");
    let n = 1usize << width;
    for i in 0..n {
        if i > 0 {
            all_rows.push_str("; ");
            if i % 4 == 0 {
                all_rows.push_str("\n    ");
            }
        }
        all_rows.push_str(&gallina_row(i, width));
    }
    all_rows.push_str(" ].");

    let mut out = String::new();
    out.push_str("(* ---- effect row domain ---- *)\n\n");
    out.push_str(&row_index_def);
    out.push_str("\n\n");
    out.push_str(&all_rows);
    out.push_str("\n\n");
    for f in &row_fns {
        out.push_str(&format!(
            "Definition {}_index_table : list nat :=\n  flat_map (fun r1 => map (fun r2 => row_index ({} r1 r2)) all_rows) all_rows.\n\n",
            f, f
        ));
    }
    for f in &bool_fns {
        out.push_str(&format!(
            "Definition {}_index_table : list nat :=\n  flat_map (fun r1 => map (fun r2 => b2n ({} r1 r2)) all_rows) all_rows.\n\n",
            f, f
        ));
    }
    out.push_str("Eval vm_compute in (length all_rows).\n\n");
    let n = 1usize << width;
    for i in 0..n {
        let r1 = gallina_row(i, width);
        for f in &row_fns {
            out.push_str(&format!(
                "Eval vm_compute in (map (fun r2 => row_index ({} ({}) r2)) all_rows).\n",
                f, r1
            ));
        }
        for f in &bool_fns {
            out.push_str(&format!(
                "Eval vm_compute in (map (fun r2 => b2n ({} ({}) r2)) all_rows).\n",
                f, r1
            ));
        }
    }
    out.push('\n');
    out
}

fn charclass_section(u: &ParseUnit) -> String {
    let fns = tabulated_byte_functions(u);
    let mut out = String::new();
    out.push_str("(* ---- charclass byte domain ---- *)\n\n");
    for f in &fns {
        out.push_str(&format!(
            "Definition {}_byte_table : list nat := map (fun b => b2n ({} b)) (seq 0 256).\n\n",
            f, f
        ));
    }
    for f in &fns {
        out.push_str(&format!("Eval vm_compute in ({}_byte_table).\n", f));
    }
    out.push('\n');
    out
}

/// The pinned 16,563-key lookup sweep, shared by the kernel oracle and the
/// Rust test: 44 sorted keys, then the empty string, then all 128 one-byte
/// ASCII strings, then all 16,384 two-byte ASCII strings, then the 6 delimiters.
pub fn sweep_keys(ref_keys: &[String]) -> Vec<Vec<u32>> {
    let mut keys: Vec<Vec<u32>> = Vec::new();
    for k in ref_keys {
        keys.push(k.chars().map(|c| c as u32).collect());
    }
    keys.push(Vec::new()); // the empty string
    for a in 0u32..128 {
        keys.push(vec![a]);
    }
    for a in 0u32..128 {
        for b in 0u32..128 {
            keys.push(vec![a, b]);
        }
    }
    for d in ["(", ")", "[", "]", "{", "}"] {
        keys.push(d.chars().map(|c| c as u32).collect());
    }
    assert_eq!(keys.len(), 16_563, "pinned sweep size");
    keys
}

fn gallina_key(codes: &[u32]) -> String {
    if codes.is_empty() {
        String::from("nil")
    } else {
        format!(
            "[{}]",
            codes
                .iter()
                .map(|c| c.to_string())
                .collect::<Vec<_>>()
                .join("; ")
        )
    }
}

